#!/usr/bin/env python3
"""Writes the Android app's data/MindAudio.kt from the same content the iOS app ships: the everyday sessions
(MensMindSession / WomenMindSession in the Swift sources), the Bible stories (Resources/mind_stories.json) and the
talks (Resources/mind_talks.json). Ids match, so the Grace voice packs "j_<id>" serve both apps.
  python3 tools/gen_android_mind.py /path/to/android/app/src/main/kotlin/com/holysteps/app/data/MindAudio.kt"""
import json, os, re, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
pat = re.compile(r'(Mens|Women)MindSession\(\s*id:\s*"([^"]+)",\s*title:\s*"([^"]*)",\s*category:\s*"([^"]*)",.*?blurb:\s*"([^"]*)",\s*script:\s*"""\n(.*?)\n"""', re.S)
items = []
for f, hub in (("Sources/Screens/MensHealth.swift", "men"), ("Sources/Screens/WomenMindView.swift", "women")):
    for n, m in enumerate(pat.finditer(open(os.path.join(root, f)).read())):
        items.append(dict(id=m.group(2), hub=hub, kind="SESSION", category=m.group(4), title=m.group(3), subtitle=m.group(5),
                          free=n < 2, sources=[], script=m.group(6)))
for s in json.load(open(os.path.join(root, "Resources/mind_stories.json"))):
    items.append(dict(s, kind="STORY", sources=[]))
for t in json.load(open(os.path.join(root, "Resources/mind_talks.json"))):
    items.append(dict(t, kind="TALK"))
assert len({i["id"] for i in items}) == len(items)
def ks(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'
def raw(s):
    assert '"""' not in s
    return '"""\n' + s.replace("$", "${'$'}") + '\n"""'
out = ["package com.holysteps.app.data", "",
       "// GENERATED by HolyStepsApple tools/gen_android_mind.py from the iOS content. Do not edit by hand.",
       "// Men's and Women's Mental Health audio: everyday sessions and talks (no faith content) and Bible stories,",
       "// all read by Grace (Kokoro af_heart, voice packs \"j_<id>\").", "",
       "enum class MindKind { SESSION, STORY, TALK }", "",
       "data class MindSource(val title: String, val url: String)", "",
       "data class MindItem(val hub: String, val kind: MindKind, val category: String, val free: Boolean,",
       "                    val sources: List<MindSource>, val journey: SanctuaryJourney)", "",
       "private fun mind(id: String, hub: String, kind: MindKind, category: String, title: String, subtitle: String,",
       "                 free: Boolean, sources: List<MindSource>, script: String) = MindItem(hub, kind, category, free, sources,",
       "    SanctuaryJourney(id = id, title = title, subtitle = subtitle, moment = SanctuaryMoment.ANXIOUS,",
       "        script = script.trimIndent().trim(), soundscape = if (kind == MindKind.STORY) Soundscape.STREAM else Soundscape.NONE,",
       "        scene = if (kind == MindKind.STORY) SceneKind.DAWN else SceneKind.DAY, premium = !free, narrator = \"af_heart\"))", "",
       "object MindLibrary {",
       "    val ALL: List<MindItem> by lazy { part1() + part2() + part3() }",
       "    private val byIdMap by lazy { ALL.associateBy { it.journey.id } }",
       "    fun byId(id: String): MindItem? = byIdMap[id]",
       "    fun list(hub: String, kind: MindKind): List<MindItem> = ALL.filter { it.hub == hub && it.kind == kind }",
       "    fun categories(hub: String, kind: MindKind): List<String> = list(hub, kind).map { it.category }.distinct()",
       ""]
chunks = [items[i::3] for i in range(3)]
# keep original order inside each part by slicing contiguously instead
n = len(items); a, b = n // 3, 2 * n // 3
chunks = [items[:a], items[a:b], items[b:]]
for k, ch in enumerate(chunks, 1):
    out.append(f"    private fun part{k}(): List<MindItem> = listOf(")
    for it in ch:
        src = "listOf(" + ", ".join(f"MindSource({ks(s['title'])}, {ks(s['url'])})" for s in it["sources"]) + ")"
        out.append(f"        mind({ks(it['id'])}, {ks(it['hub'])}, MindKind.{it['kind']}, {ks(it['category'])}, {ks(it['title'])}, {ks(it['subtitle'])},")
        out.append(f"            {'true' if it['free'] else 'false'}, {src}, {raw(it['script'])}),")
    out.append("    )"); out.append("")
out.append("}")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
from collections import Counter
print(Counter((i["hub"], i["kind"]) for i in items), len(items))
